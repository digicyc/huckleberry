#!/usr/bin/env python3
# /// script
# dependencies = ["pillow", "fonttools"]
# ///
"""Generates emoji_glyphs.c: the colour emoji HuckleBerry draws in messages and names.

Every single-code-point emoji in Noto Color Emoji (SIL Open Font License), so all the base emoji
people send from the MeshCore apps, plus the regional indicator letters that flags are made of.
ui.cpp skips the skin tones, variation selectors and joiners that modify them.

Each emoji is a 15 px image, which fits the line of every text size from 12 pt up. To fit in
flash, all of them share one 256-colour palette (with alpha), and each emoji's palette indexes
are raw-deflated; ui.cpp inflates an emoji with the ESP32-S3's ROM inflater the first time it's
shown and turns it into an LVGL RGB565A8 image.

    uv run tools/make_emoji.py > emoji_glyphs.c
"""
import argparse
import zlib

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

SIZE = 15


def wanted(c):
    modifier = (c in (0x200D, 0x20E3, 0xFE0E, 0xFE0F) or 0x1F3FB <= c <= 0x1F3FF or c >= 0xE0000)
    return c >= 0xA9 and not modifier  # below that, only text the Montserrat fonts have


def render(font, char):
    """The emoji scaled to fit a SIZE x SIZE square, centered, on a transparent background."""
    big = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(big).text((8, 8), char, font=font, embedded_color=True)
    box = big.getbbox()
    if box is None:
        raise SystemExit(f"Nothing drawn for U+{ord(char):X}")
    glyph = big.crop(box)
    scale = SIZE / max(glyph.size)
    w, h = max(1, round(glyph.width * scale)), max(1, round(glyph.height * scale))
    small = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    small.paste(glyph.resize((w, h), Image.LANCZOS), ((SIZE - w) // 2, (SIZE - h) // 2))
    return small


def c_array(kind, name, values, per_line=16):
    lines = [f"const {kind} {name}[] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines + ["};\n"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", default="/usr/share/fonts/noto/NotoColorEmoji.ttf")
    args = parser.parse_args()
    codepoints = sorted(c for c in TTFont(args.font).getBestCmap() if wanted(c))
    font = ImageFont.truetype(args.font, 109)  # its only bitmap size

    images = [render(font, chr(c)) for c in codepoints]
    sheet = Image.new("RGBA", (SIZE, SIZE * len(images)))
    for i, im in enumerate(images):
        sheet.paste(im, (0, i * SIZE))
    quantized = sheet.quantize(256, method=Image.Quantize.FASTOCTREE)
    palette = quantized.getpalette("RGBA")
    palette += [0] * (1024 - len(palette))
    indexes = quantized.tobytes()

    data, offsets = bytearray(), [0]
    for i in range(len(images)):
        deflate = zlib.compressobj(9, zlib.DEFLATED, -15)  # raw deflate, as tinfl reads it
        data += deflate.compress(indexes[i * SIZE * SIZE:(i + 1) * SIZE * SIZE]) + deflate.flush()
        offsets.append(len(data))
    rgb565 = [((palette[i] >> 3) << 11) | ((palette[i + 1] >> 2) << 5) | (palette[i + 2] >> 3)
              for i in range(0, 1024, 4)]
    alpha = palette[3::4]

    print("// Generated by tools/make_emoji.py; edit that and regenerate.")
    print("// Emoji images from Noto Color Emoji (SIL Open Font License 1.1).")
    print("#include <stdint.h>\n")
    print(f"const unsigned emoji_count = {len(codepoints)};")
    print(f"const int emoji_size = {SIZE};  // px, square")
    print(c_array("uint32_t", "emoji_codepoints", [f"0x{c:X}" for c in codepoints], 10))
    print("// emoji_data[emoji_offsets[i]] to emoji_data[emoji_offsets[i + 1]] holds emoji i.")
    print(c_array("uint32_t", "emoji_offsets", offsets, 12))
    print(c_array("uint16_t", "emoji_palette_rgb565", rgb565))
    print(c_array("uint8_t", "emoji_palette_alpha", alpha))
    print("// Each emoji's palette indexes, row by row, raw-deflated.")
    print(c_array("uint8_t", "emoji_data", list(data), 32))


if __name__ == "__main__":
    main()

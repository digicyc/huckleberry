#!/usr/bin/env python3
"""Generates src/lora_icon.c: the LoRa app's launcher icon as an LVGL A8 (alpha-only) image.

A radio mast (a dot on a pole with two legs) sending waves out to both sides. Like the other
launcher icons, the home screen tints it white with the image recolor style. Antialiased by
supersampling.

    python3 tools/make_lora_icon.py > src/lora_icon.c
"""
import math

SIZE = 30
SAMPLES = 6  # per axis, per pixel
CX, CY = 15.0, 10.0  # the dot at the top of the mast, where the waves come from
DOT_R = 2.6
WAVES = [(5.0, 7.0), (9.0, 11.0)]  # inner and outer radius of each wave
HALF_ANGLE = math.radians(38)  # each wave spans this either side of horizontal
LINE_W = 2.2


def segment(px, py, x1, y1, x2, y2, w):
    dx, dy = x2 - x1, y2 - y1
    t = max(0.0, min(1.0, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)))
    return (px - x1 - t * dx) ** 2 + (py - y1 - t * dy) ** 2 <= (w / 2) ** 2


def inside(x, y):
    dx, dy = x - CX, y - CY
    r = math.hypot(dx, dy)
    if r <= DOT_R:
        return True
    # The mast: a pole down from the dot, and two legs spreading to the base.
    if segment(x, y, CX, CY, CX, 27.5, LINE_W) or segment(x, y, CX, 17, 9.5, 27.5, LINE_W) or \
            segment(x, y, CX, 17, 20.5, 27.5, LINE_W):
        return True
    angle = math.atan2(-dy, abs(dx))  # from horizontal, on either side
    if abs(angle) <= HALF_ANGLE:
        return any(inner <= r <= outer for inner, outer in WAVES)
    return False


def pixel(x, y):
    hits = sum(inside(x + (sx + 0.5) / SAMPLES, y + (sy + 0.5) / SAMPLES)
               for sy in range(SAMPLES) for sx in range(SAMPLES))
    return round(255 * hits / SAMPLES ** 2)


print("// Generated by tools/make_lora_icon.py; edit that and regenerate.")
print('#include "lvgl.h"')
print("\nstatic const uint8_t lora_icon_map[] = {")
for y in range(SIZE):
    print("    " + ", ".join(f"0x{pixel(x, y):02x}" for x in range(SIZE)) + ",")
print("};\n")
print("const lv_image_dsc_t lora_icon = {")
print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}},")
print("    .data_size = sizeof(lora_icon_map),")
print("    .data = lora_icon_map,")
print("};")

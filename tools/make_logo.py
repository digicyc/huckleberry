"""Generates src/logo.c: the HuckleBerry logo for the boot screen, as an LVGL RGB565A8 image.

The source is tools/logo.png, a large transparent PNG. The logo is cropped to its drawing,
centered in a square and scaled down to SIZE px.

    uv run tools/make_logo.py > src/logo.c
"""
import os

from PIL import Image

SIZE = 112
SOURCE = os.path.join(os.path.dirname(__file__), "logo.png")

src = Image.open(SOURCE).convert("RGBA")
left, top, right, bottom = src.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
side = max(right - left, bottom - top)
square = Image.new("RGBA", (side, side))
square.paste(src.crop((left, top, right, bottom)), ((side - (right - left)) // 2, (side - (bottom - top)) // 2))
logo = square.resize((SIZE, SIZE), Image.LANCZOS)  # Pillow premultiplies alpha while resampling

colors, alphas = bytearray(), bytearray()
pixels = logo.tobytes()
for i in range(0, len(pixels), 4):
    r, g, b, a = pixels[i:i + 4]
    c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if a else 0
    colors += c.to_bytes(2, "little")
    alphas.append(a)
data = colors + alphas

print("// Generated by tools/make_logo.py from tools/logo.png; edit those and regenerate.")
print('#include "lvgl.h"')
print("\nstatic const uint8_t huckleberry_logo_map[] = {")
for i in range(0, len(data), 24):
    print("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
print("};\n")
print("const lv_image_dsc_t huckleberry_logo = {")
print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 2}}},")
print("    .data_size = sizeof(huckleberry_logo_map),")
print("    .data = huckleberry_logo_map,")
print("};")

#!/usr/bin/env python3
"""Generates src/contact_icons.c: the Contacts app's icons as LVGL A8 (alpha-only) images.

contacts_app_icon (30 px) is the launcher icon: two people. The 18 px ones mark each contact's type
in the list: contact_icon_companion (a person), contact_icon_repeater (a radio mast sending waves,
like the LoRa icon), contact_icon_room (a speech bubble) and contact_icon_sensor (a thermometer).
The app tints them with the image recolor style. Shapes are drawn in a unit square and antialiased
by supersampling.

    python3 tools/make_contact_icons.py > src/contact_icons.c
"""
import math

SAMPLES = 6  # per axis, per pixel


def segment(px, py, x1, y1, x2, y2, w):
    dx, dy = x2 - x1, y2 - y1
    t = max(0.0, min(1.0, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)))
    return (px - x1 - t * dx) ** 2 + (py - y1 - t * dy) ** 2 <= (w / 2) ** 2


def person(x, y, cx=0.5, scale=1.0, grow=0.0):
    """Head and shoulders centered on cx; `grow` widens it (for the gap around the front person)."""
    head = math.hypot(x - cx, y - 0.30 * scale - (1 - scale) * 0.2) <= 0.19 * scale + grow
    by = 0.98 * scale + (1 - scale) * 0.2
    rx, ry = 0.36 * scale + grow, 0.40 * scale + grow
    body = y <= 0.94 * scale + (1 - scale) * 0.2 + grow and ((x - cx) / rx) ** 2 + ((y - by) / ry) ** 2 <= 1
    return head or body


def people(x, y):
    front = person(x, y, cx=0.37)
    back = person(x, y, cx=0.68, scale=0.8) and not person(x, y, cx=0.37, grow=0.07)
    return front or back


def repeater(x, y):
    cx, cy = 0.5, 0.33
    r = math.hypot(x - cx, y - cy)
    if r <= 0.10:
        return True
    w = 0.11
    if segment(x, y, cx, cy, cx, 0.94, w) or segment(x, y, cx, 0.58, 0.30, 0.94, w) or \
            segment(x, y, cx, 0.58, 0.70, 0.94, w):
        return True
    if abs(math.atan2(-(y - cy), abs(x - cx))) <= math.radians(40):
        return 0.18 <= r <= 0.27 or 0.35 <= r <= 0.45
    return False


def room(x, y):
    # A rounded speech bubble with a tail at the lower left.
    left, right, top, bottom, rad = 0.06, 0.94, 0.12, 0.70, 0.16
    qx = min(max(x, left + rad), right - rad)
    qy = min(max(y, top + rad), bottom - rad)
    bubble = math.hypot(x - qx, y - qy) <= rad
    tail = 0.62 <= y <= 0.92 and 0.22 <= x <= min(0.22 + (0.92 - y) * 0.9, 0.48)
    return bubble or tail


def sensor(x, y):
    bulb = math.hypot(x - 0.5, y - 0.74) <= 0.20
    stem = segment(x, y, 0.5, 0.18, 0.5, 0.70, 0.24)
    return bulb or stem


def emit(name, inside, size):
    def pixel(px, py):
        hits = sum(inside((px + (sx + 0.5) / SAMPLES) / size, (py + (sy + 0.5) / SAMPLES) / size)
                   for sy in range(SAMPLES) for sx in range(SAMPLES))
        return round(255 * hits / SAMPLES ** 2)

    print(f"\nstatic const uint8_t {name}_map[] = {{")
    for py in range(size):
        print("    " + ", ".join(f"0x{pixel(px, py):02x}" for px in range(size)) + ",")
    print("};\n")
    print(f"const lv_image_dsc_t {name} = {{")
    print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {size}, .h = {size}, .stride = {size}}},")
    print(f"    .data_size = sizeof({name}_map),")
    print(f"    .data = {name}_map,")
    print("};")


print("// Generated by tools/make_contact_icons.py; edit that and regenerate.")
print('#include "lvgl.h"')
emit("contacts_app_icon", people, 30)
emit("contact_icon_companion", person, 18)
emit("contact_icon_repeater", repeater, 18)
emit("contact_icon_room", room, 18)
emit("contact_icon_sensor", sensor, 18)
